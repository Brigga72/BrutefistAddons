local function regionName(region)
    if not region then return "not found" end
    local ok, name = pcall(region.GetDebugName, region)
    return ok and tostring(name) or "found (unnamed)"
end

-- The frame whose visibility decides whether the display shows (a hidden target frame means the marker would
-- float over nothing), and the top-level frame to layer above. Both follow the attached frames.
local visibilityFrame, layerRoot
local attachedSignature

-- Attaches the display to the preview, the custom frames (Advanced options) or Blizzard's target frame.
-- Without `force`, only re-attaches if the frames to use changed (custom frames may be created late, or
-- rebuilt by their addon), so it's cheap to call on every target change.
local function attach(force)
    local portrait, bar, customBar, customAnchor, typedBar, knownPortrait, knownOwner
    if previewHost then
        portrait, bar = previewHost.portrait, previewHost.healthBar
    else
        typedBar = ns.resolveFramePath(db.customHealthBar)
        -- Without a working path, a known replacement target frame (EllesmereUI's) comes before Blizzard's.
        if typedBar then
            customBar = typedBar
        else
            customBar, knownPortrait, knownOwner = ns.knownTargetFrame()
        end
        customAnchor = ns.resolveFramePath(db.customIconAnchor)
        bar = customBar or findTargetHealthBar()
        -- Replacement frames often have no portrait; the kill icon then sits on their health bar (offsets move it).
        portrait = customAnchor or knownPortrait or (customBar == nil and findTargetPortrait()) or nil
    end
    local signature = tostring(previewHost) .. tostring(bar) .. tostring(portrait)
    if not force and signature == attachedSignature then return portrait ~= nil end
    attachedSignature = signature

    skullAnchor = portrait or customBar or TargetFrame or UIParent
    local custom = customBar or customAnchor
    visibilityFrame = (not previewHost) and (custom or TargetFrame) or nil
    layerRoot = custom and ns.frameRoot(custom) or TargetFrame
    plainSkullFrame:ClearAllPoints()
    plainSkullFrame:SetPoint("BOTTOM", skullWindow, "TOP", 0, 4)

    healthBar = bar
    if healthBar then
        remainingBar:ClearAllPoints()
        remainingBar:SetAllPoints(healthBar)
    end
    appliedSignature = nil -- re-anchor the skull, label and effects against the (new) frames
    local function describeSetting(path, found, fallback)
        if path == "" then return fallback and (" (" .. fallback .. ")") or "" end
        return found and (" (custom " .. path .. ")")
            or (" (custom " .. path .. " NOT FOUND, using " .. (fallback or "Blizzard's") .. ")")
    end
    trace("ATTACH portrait: " .. regionName(portrait) .. describeSetting(db.customIconAnchor, customAnchor)
        .. " | health bar: " .. regionName(healthBar)
        .. describeSetting(db.customHealthBar, typedBar, knownOwner and (knownOwner .. " target frame")))
    return portrait ~= nil or customBar ~= nil
end

-- What the display is attached to, for the options window: health bar and icon lines.
function ns.attachStatus()
    local function line(path, found, fallback)
        if strtrim(path) == "" then return fallback end
        if found then return "|cff66ff66" .. strtrim(path) .. "|r" end
        return "|cffff6666" .. strtrim(path) .. " not found|r, using " .. fallback
    end
    local customBar = ns.resolveFramePath(db.customHealthBar)
    local knownBar, knownPortrait, knownOwner
    if not customBar then knownBar, knownPortrait, knownOwner = ns.knownTargetFrame() end
    local iconFallback = knownPortrait and (knownOwner .. " portrait")
        or (customBar or knownBar) and "the health bar" or "Blizzard's portrait"
    local barFallback = knownOwner and (knownOwner .. " target frame") or "Blizzard's target frame"
    return line(db.customHealthBar, customBar, barFallback),
        line(db.customIconAnchor, ns.resolveFramePath(db.customIconAnchor), iconFallback)
end

local STRATA_RANK = {
    BACKGROUND = 1, LOW = 2, MEDIUM = 3, HIGH = 4, DIALOG = 5, FULLSCREEN = 6, FULLSCREEN_DIALOG = 7, TOOLTIP = 8,
}
local LAYER_CHECK_INTERVAL = 1

-- Highest strata/level anywhere in the target frame's tree. Blizzard (Edit Mode) re-layers the target
-- frame after addons load, so a level picked once at load ends up underneath the health bar and portrait.
local function targetFrameTopLayer()
    local topStrata, topLevel = "BACKGROUND", 0
    local function visit(frame, depth)
        -- Some of Blizzard's frames report a secret strata/level in Forever; those can't be compared, so skip
        -- them (their children are still visited).
        local strata, level = frame:GetFrameStrata(), frame:GetFrameLevel()
        if not isSecret(strata) and not isSecret(level) then
            local rank, topRank = STRATA_RANK[strata] or 0, STRATA_RANK[topStrata] or 0
            if rank > topRank then
                topStrata, topLevel = strata, level
            elseif rank == topRank and level > topLevel then
                topLevel = level
            end
        end
        if depth < 6 then
            for _, child in ipairs({ frame:GetChildren() }) do visit(child, depth + 1) end
        end
    end
    visit(layerRoot or healthBar or UIParent, 0)
    return topStrata, topLevel
end

-- Keeps our marker and skull above everything on the target frame. Checked while displaying (throttled)
-- because Blizzard can re-layer the frame at any time.
local layerCheckedAt, lastStrata, lastLevel, layerErrorLogged = 0, nil, nil, false
local function updateLayering(now)
    if now - layerCheckedAt < LAYER_CHECK_INTERVAL then return end
    layerCheckedAt = now
    local ok, strata, level
    if previewHost then
        -- One strata above the options window: it's a top-level frame, which WoW raises above everything else
        -- in its own strata (our frames included) when it's shown or clicked. Dropdowns and tooltips sit higher.
        ok, strata, level = true, "FULLSCREEN", 1
    else
        ok, strata, level = pcall(targetFrameTopLayer)
    end
    if not ok then
        if not layerErrorLogged then
            layerErrorLogged = true
            trace("LAYER check failed (logged once): " .. tostring(strata))
        end
        return
    end
    for i, frame in ipairs({ remainingBar, fillLayer, clipLayer, outlineLayer, sparkLayer, skullWindow, skullBar }) do
        frame:SetFrameStrata(strata)
        frame:SetFrameLevel(level + i)
    end
    if strata ~= lastStrata or level ~= lastLevel then
        lastStrata, lastLevel = strata, level
        trace(string.format("LAYER target frame top is %s/%d; marker and skull placed above it", strata, level))
    end
end

